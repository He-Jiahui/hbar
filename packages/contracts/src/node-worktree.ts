import { z } from 'zod'
import { nodeWorktreeProvisioningAuthoritySchema } from './node-worktree-provisioning'
import { nodeRootIdSchema } from './node-address'
import { sha256Hex } from './sha256'

/**
 * Requests a worktree by a B-owned stable id. Callers never choose a filesystem
 * path; B derives it beneath the registered root and persists its ownership.
 */
export const nodeWorktreeCreateSchema = z
  .strictObject({
    operationId: z.string().min(1).max(330),
    rootId: nodeRootIdSchema,
    expectedRoot: z.string().min(1).max(4_000),
    provisioning: nodeWorktreeProvisioningAuthoritySchema,
    branch: z
      .string()
      .trim()
      .min(1)
      .max(255)
      .regex(/^[A-Za-z0-9][A-Za-z0-9._/-]{0,254}$/)
      .refine(
        (value) =>
          !value.startsWith('-') &&
          !value.startsWith('/') &&
          !value.endsWith('/') &&
          !value.endsWith('.') &&
          !value.includes('..') &&
          !value.includes('//') &&
          !value.includes('@{') &&
          !value.split('/').some((part) => part.startsWith('.') || part.endsWith('.lock')),
        'Branch must be a valid local Git branch name',
      ),
    startPoint: z
      .string()
      .trim()
      .min(1)
      .max(255)
      .regex(/^[A-Za-z0-9][A-Za-z0-9._/-]{0,254}$/)
      .optional(),
    createBranch: z.boolean().default(false),
  })
  .superRefine((input, context) => {
    const { selection } = input.provisioning
    const fail = (path: (string | number)[], message: string) => context.addIssue({ code: 'custom', path, message })
    if (selection.mode === 'shared-current') return
    if (selection.mode === 'shared-branch') {
      if (input.branch !== selection.branch.ref.slice('refs/heads/'.length))
        fail(['branch'], 'Branch differs from selection')
      if (input.createBranch || input.startPoint !== undefined)
        fail(['createBranch'], 'Shared branch selection must check out the existing branch')
      return
    }
    switch (selection.branch.kind) {
      case 'existing':
        if (input.branch !== selection.branch.name) fail(['branch'], 'Branch differs from selection')
        if (input.createBranch || input.startPoint !== undefined)
          fail(['createBranch'], 'Existing branch selection must check out the existing branch')
        break
      case 'new':
        if (input.branch !== selection.branch.name) fail(['branch'], 'Branch differs from selection')
        if (!input.createBranch || input.startPoint !== selection.branch.startPoint)
          fail(['startPoint'], 'New branch plan differs from the accepted selection')
        break
      case 'derived': {
        const expectedBranch = `hbar/session-launch/${sha256Hex(`${input.provisioning.sessionId}\0${input.provisioning.targetRevision}`)}`
        const expectedStartPoint = selection.branch.baseRef.slice('refs/heads/'.length)
        if (input.branch !== expectedBranch) fail(['branch'], 'Derived branch differs from the accepted selection')
        if (!input.createBranch || input.startPoint !== expectedStartPoint)
          fail(['startPoint'], 'Derived branch plan differs from the accepted selection')
        break
      }
    }
  })

export const nodeWorktreeRemoveSchema = z.strictObject({
  operationId: z.string().min(1).max(330),
  rootId: nodeRootIdSchema,
  expectedRoot: z.string().min(1).max(4_000),
  worktreeId: z.string().regex(/^[a-f0-9]{32}$/),
  provisioning: nodeWorktreeProvisioningAuthoritySchema,
})

export const nodeManagedWorktreeSchema = z.strictObject({
  worktreeId: z.string().regex(/^[a-f0-9]{32}$/),
  sessionId: z.string().min(1).max(160),
  createdByRunId: z.string().min(1).max(160),
  targetRevision: z.number().int().nonnegative().safe(),
  /** Ephemeral B capability registered for this managed worktree. */
  worktreeRootId: nodeRootIdSchema,
  parentRootId: nodeRootIdSchema,
  /** The canonical B path returned for execution; generated by B under root. */
  nodePath: z.string().min(1).max(4_000),
  branch: z.string().min(1).max(255),
  createdAt: z.number().int().nonnegative().safe(),
})

const worktreeTargetSchema = z.strictObject({
  operationId: z.string().min(1).max(330),
  rootId: nodeRootIdSchema,
  expectedRoot: z.string().min(1).max(4_000),
  provisioning: nodeWorktreeProvisioningAuthoritySchema,
  branch: nodeWorktreeCreateSchema.shape.branch,
  startPoint: nodeWorktreeCreateSchema.shape.startPoint,
  createBranch: z.boolean(),
})
/** Named B allocator operations; all targets are generated from IDs on B. */
export const nodeWorktreeMethods = {
  'worktree.create': {
    input: nodeWorktreeCreateSchema,
    output: nodeManagedWorktreeSchema,
  },
  'worktree.remove': {
    input: nodeWorktreeRemoveSchema,
    output: z.strictObject({ accepted: z.literal(true) }),
  },
  'worktree.get': {
    input: worktreeTargetSchema,
    output: nodeManagedWorktreeSchema.nullable(),
  },
} as const

export type NodeWorktreeMethod = keyof typeof nodeWorktreeMethods

export type NodeWorktreeCreate = z.infer<typeof nodeWorktreeCreateSchema>
export type NodeWorktreeCreateRequest = z.input<typeof nodeWorktreeCreateSchema>
export type NodeWorktreeRemove = z.infer<typeof nodeWorktreeRemoveSchema>
export type NodeManagedWorktree = z.infer<typeof nodeManagedWorktreeSchema>
