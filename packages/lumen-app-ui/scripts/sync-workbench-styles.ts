import ts from 'typescript'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '../src')
const manifest = resolve(root, 'workbench-component-styles.ts')
const baseStyles = new Set<string>()
const read = (file: string) => readFileSync(file, 'utf8')
function visitCss(file: string): void {
  if (baseStyles.has(file) || file === manifest) return
  baseStyles.add(file)
  for (const match of read(file).matchAll(/@import\s+['"]([^'"]+)['"]/g)) {
    if (match[1]?.startsWith('.')) visitCss(resolve(dirname(file), match[1]))
  }
}
visitCss(resolve(root, 'styles.css'))

const visited = new Set<string>()
const componentStyles = new Set<string>()
function visitModule(file: string): void {
  if (visited.has(file)) return
  visited.add(file)
  const source = ts.createSourceFile(file, read(file), ts.ScriptTarget.Latest, true)
  for (const node of source.statements) {
    if (!ts.isImportDeclaration(node) && !ts.isExportDeclaration(node)) continue
    if (ts.isImportDeclaration(node) && node.importClause?.isTypeOnly) continue
    if (ts.isExportDeclaration(node) && node.isTypeOnly) continue
    const specifier = node.moduleSpecifier
    if (!specifier || !ts.isStringLiteral(specifier) || !specifier.text.startsWith('.')) continue
    const target = resolve(dirname(file), specifier.text)
    if (target.endsWith('.css')) {
      componentStyles.add(target)
      continue
    }
    const module = [target + '.ts', target + '.tsx', resolve(target, 'index.ts')].find(existsSync)
    if (!module) throw new Error(`Cannot resolve public composition dependency: ${specifier.text} from ${file}`)
    visitModule(module)
  }
}
visitModule(resolve(root, 'index.ts'))
const output =
  '// Generated by scripts/sync-workbench-styles.ts from the public workbench module graph.\n' +
  "import './styles.css'\n" +
  [...componentStyles]
    .filter((file) => !baseStyles.has(file))
    .sort()
    .map((file) => `import './${relative(root, file).replaceAll('\\', '/')}'`)
    .join('\n') +
  '\n'
if (process.argv.includes('--check')) {
  if (!existsSync(manifest) || read(manifest) !== output)
    throw new Error('Workbench style manifest is stale; run the package build.')
} else if (!existsSync(manifest) || read(manifest) !== output) writeFileSync(manifest, output)
console.log(`Workbench style manifest: ${componentStyles.size} component CSS modules, ${visited.size} source modules.`)
