import type { LumenFilteringReferenceContent as Content, LumenFilteringReferenceField as Field, LumenFilteringReferenceOption as Option } from '@lumen/app-ui/catalog'

const options = (values: readonly (string | readonly [string, string, string?])[]): readonly Option[] =>
  values.map((value) =>
    typeof value === 'string'
      ? { id: value, label: value }
      : { id: value[0], label: value[1], ...(value[2] === undefined ? {} : { detail: value[2] }) },
  )
const single = (
  id: string,
  label: string,
  values: readonly (string | readonly [string, string, string?])[],
  value: string,
  placement: Field['placement'] = 'facet',
  display: 'pills' | 'select' | 'radio' | 'rail' = 'pills',
): Extract<Field, { kind: 'single' }> => ({
  id,
  label,
  kind: 'single',
  options: options(values),
  value,
  placement,
  display,
})
const multi = (
  id: string,
  label: string,
  values: readonly (string | readonly [string, string, string?])[],
  display: 'checks' | 'pills' | 'swatches' | 'menu' = 'checks',
  placement: Field['placement'] = 'facet',
): Extract<Field, { kind: 'multi' }> => ({
  id,
  label,
  kind: 'multi',
  options: options(values),
  value: [],
  placement,
  display,
})
const range = (
  id: string,
  label: string,
  minimum: number,
  maximum: number,
  endpointLabels: readonly [string, string],
  valueLabel: (lower: number, upper: number) => string,
  step = 1,
): Field => ({
  id,
  label,
  kind: 'range',
  minimumId: `${id}-minimum`,
  maximumId: `${id}-maximum`,
  minimum,
  maximum,
  step,
  value: [minimum, maximum],
  valueLabel,
  endpointLabels,
  placement: 'facet',
})
const text = (id: string, label: string, placeholder: string): Field => ({
  id,
  label,
  kind: 'text',
  value: '',
  placeholder,
  placement: 'toolbar',
})
const money = (value: number) => `$${value.toLocaleString('en-US')}`
