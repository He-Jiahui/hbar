import { createHash } from 'node:crypto'
import { join } from 'node:path'

export const SANDBOX_EVALUATOR_SOURCES = [
  'packages/sandbox/src/policy.ts',
  'packages/sandbox/src/gate.ts',
  'packages/sandbox/src/snapshot.ts',
  'packages/contracts/src/sandbox.ts',
] as const
export async function sandboxEvaluatorSourceFingerprint(root: string): Promise<string> {
  const hash = createHash('sha256').update('hbar.sandbox.evaluator.v1\0')
  for (const path of SANDBOX_EVALUATOR_SOURCES) {
    const source = await Bun.file(join(root, path)).text()
    hash.update(path + '\0' + source.replaceAll('\r\n', '\n'))
  }
  return hash.digest('hex')
}
if (import.meta.main) {
  const root = join(import.meta.dir, '..')
  const digest = await sandboxEvaluatorSourceFingerprint(root)
  const output = join(root, 'packages/sandbox/src/evaluator-fingerprint.ts')
  const expected = `// Generated by scripts/generate-sandbox-evaluator.ts; regenerate when evaluator sources change.\nexport const SANDBOX_EVALUATOR_FINGERPRINT = '${digest}'\n`
  if (Bun.argv.includes('--check')) {
    if ((await Bun.file(output).text()).replaceAll('\r\n', '\n') !== expected)
      throw new Error('Sandbox evaluator fingerprint is stale')
  } else await Bun.write(output, expected)
}
