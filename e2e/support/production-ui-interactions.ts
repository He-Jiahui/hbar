export function interactionAppliesTo(
  interactionDefinition: ProductionUiInteraction,
  platform: Exclude<ProductionUiPlatform, 'both'>,
): boolean {
  return interactionDefinition.platforms === 'both' || interactionDefinition.platforms === platform
}

export function getProductionUiInteraction(id: string): ProductionUiInteraction | undefined {
  return productionUiInteractions.find((candidate) => candidate.id === id)
}
