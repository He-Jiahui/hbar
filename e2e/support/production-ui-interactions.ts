export const productionUiSurfaces = [
  'shell',
  'session',
  'settings',
  'status',
  'files',
  'monitoring',
  'agents',
  'goals',
  'commands',
  'settings-editor',
] as const

export type ProductionUiSurface = (typeof productionUiSurfaces)[number]
export type ProductionUiPlatform = 'web' | 'tauri' | 'both'
export type ProductionUiEvidence = 'before-screenshot' | 'after-screenshot' | 'aria' | 'geometry' | 'host-fact'

export type ProductionUiTrigger =
  | Readonly<{ kind: 'accessible'; role: string; name: string }>
  | Readonly<{ kind: 'shortcut'; keys: string }>
  | Readonly<{ kind: 'component'; action: string }>

export type ProductionUiEffect = Readonly<{
  kind: 'command-read' | 'command-write' | 'component-state'
  name: string
}>

export type ProductionUiResult = Readonly<{
  visible: string
  host?: string
  focus?: string
  return?: string
}>

export type ProductionUiReference = Readonly<{
  kind: 'cc-haha-shared' | 'hbar-specific' | 'native'
  pattern: string
}>

export type ProductionUiInteraction = Readonly<{
  id: string
  surface: ProductionUiSurface
  precondition: readonly string[]
  trigger: ProductionUiTrigger
  effect: ProductionUiEffect
  result: ProductionUiResult
  platforms: ProductionUiPlatform
  evidence: readonly ProductionUiEvidence[]
  reference: ProductionUiReference
}>

const commonEvidence = ['before-screenshot', 'after-screenshot', 'aria', 'geometry'] as const
const writeEvidence = [...commonEvidence, 'host-fact'] as const

type InteractionSeed = Omit<ProductionUiInteraction, 'evidence' | 'reference'> &
  Partial<Pick<ProductionUiInteraction, 'evidence' | 'reference'>>

function interaction(seed: InteractionSeed): ProductionUiInteraction {
  return {
    ...seed,
    evidence:
      seed.evidence ?? (seed.effect.kind === 'command-write' || seed.result.host ? writeEvidence : commonEvidence),
    reference: seed.reference ?? { kind: 'cc-haha-shared', pattern: seed.id },
  }
}

const accessible = (role: string, name: string): ProductionUiTrigger => ({ kind: 'accessible', role, name })
const shortcut = (keys: string): ProductionUiTrigger => ({ kind: 'shortcut', keys })
const component = (action: string): ProductionUiTrigger => ({ kind: 'component', action })
const local = (name: string): ProductionUiEffect => ({ kind: 'component-state', name })
const read = (name: string): ProductionUiEffect => ({ kind: 'command-read', name })
const write = (name: string): ProductionUiEffect => ({ kind: 'command-write', name })

