import { expect, test } from '@playwright/test'
import { mountLumenFixture } from './support/lumen-controls-fixture'
import type {} from '../tests/fixtures/sidebar-tree-browser'

test('tree owns roving focus, hierarchy, arrows, type-ahead and independent actions', async ({ page }) => {
  await mountLumenFixture(page, 'tests/fixtures/sidebar-tree-browser.tsx')
  const alpha = page.getByRole('treeitem', { name: 'Alpha', exact: true })
  const bravo = page.getByRole('treeitem', { name: 'Bravo', exact: true })
  const charlie = page.getByRole('treeitem', { name: 'Charlie', exact: true })
  const delta = page.getByRole('treeitem', { name: 'Delta', exact: true })
  const zulu = page.getByRole('treeitem', { name: 'Zulu', exact: true })
  await alpha.focus()
  await alpha.press('ArrowRight')
  await expect(bravo).toBeFocused()
  await bravo.press('ArrowRight')
  await expect(charlie).toHaveAttribute('aria-level', '3')
  await bravo.press('ArrowRight')
  await expect(charlie).toBeFocused()
  await charlie.press('ArrowDown')
  await expect(delta).toBeFocused()
  await delta.press('ArrowUp')
  await expect(charlie).toBeFocused()
  await charlie.press('ArrowLeft')
  await expect(bravo).toBeFocused()
  await bravo.press('ArrowLeft')
  await expect(charlie).toHaveCount(0)
  await bravo.press('End')
  await expect(zulu).toBeFocused()
  await zulu.press('Home')
  await expect(alpha).toBeFocused()
  await alpha.press('z')
  await expect(zulu).toBeFocused()
  expect(await page.evaluate(() => window.sidebarTreeFixture.events())).toEqual([])
  await zulu.press('Enter')
  expect(await page.evaluate(() => window.sidebarTreeFixture.events())).toEqual(['activate:zulu'])
  await page.getByRole('button', { name: 'Rename Alpha', exact: true }).click()
  await expect(alpha).toHaveAttribute('aria-expanded', 'true')
  expect(await page.evaluate(() => window.sidebarTreeFixture.events())).toEqual(['activate:zulu', 'action:alpha'])
  await page.evaluate(() => window.sidebarTreeFixture.duplicate())
  await expect(page.locator('[role="treeitem"][tabindex="0"]')).toHaveCount(1)
})

test('removing a focused asynchronous child returns to the surviving parent without stealing other input focus', async ({
  page,
}) => {
  await mountLumenFixture(page, 'tests/fixtures/sidebar-tree-browser.tsx')
  const bravo = page.getByRole('treeitem', { name: 'Bravo', exact: true })
  const charlie = page.getByRole('treeitem', { name: 'Charlie', exact: true })
  await bravo.focus()
  await bravo.press('ArrowRight')
  await charlie.focus()
  await page.evaluate(() => window.sidebarTreeFixture.removeChild())
  await expect(bravo).toBeFocused()
  const input = page.getByRole('textbox', { name: 'Outside input', exact: true })
  await input.focus()
  await page.evaluate(() => window.sidebarTreeFixture.duplicate())
  await expect(input).toBeFocused()
})
